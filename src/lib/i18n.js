function flatten(obj, prefix = '', out = {}) {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object' && !Array.isArray(v)) flatten(v, key, out);
    else out[key] = v;
  }
  return out;
}

const DICT = { es: flatten(es), en: flatten(en) };

export function translate(locale, key, vars) {
  const table = DICT[locale] || DICT.es;
  let s = table[key];
  if (s === undefined) s = DICT.es[key];
  if (s === undefined) return key;
  if (!vars) return s;
  return String(s).replace(/\{(\w+)\}/g, (m, name) => (vars[name] === null || vars[name] === undefined ? '' : String(vars[name])));
}

export const I18nContext = createContext({ locale: 'es', t: (k, v) => translate('es', k, v), setLocale: () => {} });
export const useI18n = () => useContext(I18nContext);

/** Fechas y números con el formato del idioma activo. */
export function makeFormatters(locale) {
  const tag = LOCALE_TAG[locale] || LOCALE_TAG.es;
  return {
    date: (iso, opts = { day: 'numeric', month: 'short' }) => (iso ? new Date(iso.length === 10 ? `${iso}T12:00:00` : iso).toLocaleDateString(tag, opts) : ''),
    dateTime: (iso) => (iso ? new Date(iso).toLocaleString(tag, { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' }) : ''),
    num: (n, d = 1) => (n === null || n === undefined || !Number.isFinite(Number(n)) ? null : Number(n).toLocaleString(tag, { minimumFractionDigits: d, maximumFractionDigits: d }))
  };
}

